#!/usr/bin/env python3
"""Validate this experiment's evidence and regenerate numerical summaries."""
import hashlib,itertools,json,statistics
from pathlib import Path
root=Path(__file__).resolve().parent
read=lambda name:json.loads((root/name).read_text())
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
median=statistics.median
build=read('build.json');timers=read('timers.json');echo=read('echo.json');mixed=read('mixed.json');stat=read('stat/results.json');mbuild=read('mixed-build.json')
assert build['source']=='0d2c4f1c3fa0c2e502531880dab0acba18f097c0'
assert build['patch_sha256']==sha(root/'candidate.patch')
for data,script in [(timers,'run-timers.py'),(stat,'stat-timers.py')]:
 assert data['build']==build
 assert data['runner_sha256']==sha(root/'scripts'/script)
 assert data['timer_slack_ns']==1
for data,b in [(echo,build),(mixed,mbuild)]:
 assert data['build']==b
 assert data['runner']['sha256']==sha(root/'scripts/run.py')
 assert data['helper']['sha256']==sha(root/'scripts/sample-runner.py')
 assert data['client']['sha256']=='db6c914ab75011477ec6232e681046b1e75532cbaa1c81663bac984591675cf3'
assert mbuild['harness_sha256']==sha(root/'scripts/mixed-server.rs')
provenance=read('provenance.json')
assert provenance['source_patch_verified_sha256']==sha(root/'candidate.patch')
assert provenance['harness_sha256']==sha(root/'scripts/timers.rs')
assert provenance['mixed_server_sha256']==mbuild['harness_sha256']
for variant in ['before','local']:
 for name,fingerprint in build['binaries'][variant].items():
  assert provenance['binaries'][variant][name]==fingerprint['sha256']
for data,metadata in [(echo,build),(mixed,mbuild)]:
 for case in data['cases']:
  expected=metadata['binaries'][case['label']]
  if data is echo:expected=expected['core-scheduler-echo-benchmark']
  assert case['binary']==expected
workloads=[(1,1,10),(1,1,1000),(1,32,1000),(4,1,1000),(4,32,1000),(4,1024,1000)]
expected={(v,b,w,n,d,r) for r in range(1,4) for v,b in itertools.product(['before','local'],['iouring','native']) for w,n,d in workloads if b=='iouring' or (w,n,d) in [(1,1,1000),(4,1024,1000)]}
actual=[(s['variant'],s['backend'],s['workers'],s['tasks'],s['delay_us'],s['repeat']) for s in timers['samples']]
assert len(actual)==len(set(actual)) and set(actual)==expected
for data,backends,loads in [(echo,['iouring','iouring-poll','tokio'],[(1,1,64),(1,32,64),(4,128,64)]),(mixed,['iouring','iouring-poll'],[(1,32,64),(4,128,64)])]:
 expected={(v,b,w,n,z,r) for v,b,(w,n,z),r in itertools.product(['before','local'],backends,loads,range(1,4))}
 actual=[(s['variant'],s['backend'],s['workers'],s['connections'],s['bytes'],s['repeat']) for s in data['samples']]
 assert len(actual)==len(set(actual)) and set(actual)==expected
expected={(v,w,n,d,r) for v,(w,n,d),r in itertools.product(['before','local'],[(1,1,1000),(4,1024,1000)],range(1,3))}
actual=[(s['variant'],s['workers'],s['tasks'],s['delay_us'],s['repeat']) for s in stat['samples']]
assert len(actual)==len(set(actual)) and set(actual)==expected
summary={'timers':[],'echo':[],'mixed':[],'stat':[]}
def group(data,variant,backend,w,n,z):
 key='tasks' if data is timers else 'connections';size='delay_us' if data is timers else 'bytes'
 return [s for s in data['samples'] if (s['variant'],s['backend'],s['workers'],s[key],s[size])==(variant,backend,w,n,z)]
def timer_group(v,b,w,n,d):
 ss=group(timers,v,b,w,n,d)
 result={k:median(s[k] for s in ss) for k in ['expiries_per_second','lateness_p50_us','lateness_p99_us','threads_at_250ms','voluntary_switches','involuntary_switches']}
 result['cpu_seconds']=median(s['user_seconds']+s['system_seconds'] for s in ss)
 result['rate_range']=[min(s['expiries_per_second'] for s in ss),max(s['expiries_per_second'] for s in ss)]
 return result
lines=['# Worker-owned timer measurements','','Generated by `summarize.py`. All uninstrumented values are medians of three randomized repetitions. Timer CPU covers the whole process (one second warmup, three measured seconds, startup and shutdown); histogram rates cover the measurement window only.','','## Periodic timers, matching 1 ns timer slack','','| Backend | Workers / tasks / delay µs | Before → local expiries/s | Before → local p50 lateness µs | Before → local p99 µs | Before → local CPU seconds | CPU change |','| --- | --- | ---: | ---: | ---: | ---: | ---: |']
for b in ['iouring','native']:
 for w,n,d in workloads:
  if not group(timers,'before',b,w,n,d):continue
  old=timer_group('before',b,w,n,d);new=timer_group('local',b,w,n,d)
  change=100*(new['cpu_seconds']/old['cpu_seconds']-1)
  summary['timers'].append({'backend':b,'workers':w,'tasks':n,'delay_us':d,'before':old,'local':new,'cpu_change_percent':change})
  lines.append(f"| {b} | {w}/{n}/{d} | {old['expiries_per_second']:,.0f} → {new['expiries_per_second']:,.0f} | {old['lateness_p50_us']:.2f} → {new['lateness_p50_us']:.2f} | {old['lateness_p99_us']:.2f} → {new['lateness_p99_us']:.2f} | {old['cpu_seconds']:.3f} → {new['cpu_seconds']:.3f} | {change:+.1f}% |")
for data,name,title in [(echo,'echo','Echo without application timers'),(mixed,'mixed','Echo with 32 concurrent 1 ms timers')]:
 lines+=['','## '+title,'','| Backend | Workers / connections / bytes | Before requests/s (range) | Local requests/s (range) | Change |','| --- | --- | ---: | ---: | ---: |']
 for w,n,z in [tuple(x) for x in data['workloads']]:
  for b in (['iouring','iouring-poll','tokio'] if data is echo else ['iouring','iouring-poll']):
   values={}
   for v in ['before','local']:
    ss=group(data,v,b,w,n,z);rates=[s['requests_per_second'] for s in ss]
    value={'requests_per_second':median(rates),'min':min(rates),'max':max(rates)}
    if data is mixed:
     observations=[read('mixed-stderr/'+s['identifier']+'.stderr') for s in ss]
     assert all(o['tasks']==32 for o in observations)
     value.update(timer_p50_us=median(o['lateness_p50_us'] for o in observations),timer_p99_us=median(o['lateness_p99_us'] for o in observations),completed=median(o['completed'] for o in observations))
    values[v]=value
   old=values['before'];new=values['local'];change=100*(new['requests_per_second']/old['requests_per_second']-1)
   row={'backend':b,'workers':w,'connections':n,'bytes':z,**values,'change_percent':change};summary[name].append(row)
   lines.append(f"| {b} | {w}/{n}/{z} | {old['requests_per_second']:,.0f} ({old['min']:,.0f}–{old['max']:,.0f}) | {new['requests_per_second']:,.0f} ({new['min']:,.0f}–{new['max']:,.0f}) | {change:+.2f}% |")
 if data is mixed:
  lines+=['','Timers run alongside echo tasks; both variants inherit 1 ns timer slack. Lateness is recorded after the first second until echo completes. This window approximates the client measurement window; it is not synchronized to its exact boundaries.','','| Backend | Workers / connections | Before → local timer p50 µs | Before → local timer p99 µs |','| --- | --- | ---: | ---: |']
  for s in summary['mixed']:
   old=s['before'];new=s['local'];lines.append(f"| {s['backend']} | {s['workers']}/{s['connections']} | {old['timer_p50_us']:.2f} → {new['timer_p50_us']:.2f} | {old['timer_p99_us']:.2f} → {new['timer_p99_us']:.2f} |")
lines+=['','## Separate instrumented diagnostics','','Whole-process `perf stat` medians of two runs, including warmup and startup/shutdown. These counts are separate from the uninstrumented throughput measurements. Both inherit 1 ns timer slack.','','| Workers / tasks / delay µs | Version | Instructions | Context switches | Ring enters | Futex calls | Reads | Writes |','| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
for w,n,d in [(1,1,1000),(4,1024,1000)]:
 for v in ['before','local']:
  counts={}
  for s in stat['samples']:
   if (s['variant'],s['workers'],s['tasks'],s['delay_us'])!=(v,w,n,d):continue
   for line in (root/'stat'/(s['identifier']+'.stat')).read_text().splitlines():
    parts=line.split(';')
    if len(parts)<3 or parts[0].startswith('#'):continue
    try:value=float(parts[0])
    except ValueError:continue
    counts.setdefault(parts[2].strip(),[]).append(value)
  counts={k:median(vs) for k,vs in counts.items()}
  summary['stat'].append({'variant':v,'workers':w,'tasks':n,'delay_us':d,'counts':counts})
  names=['instructions','context-switches','syscalls:sys_enter_io_uring_enter','syscalls:sys_enter_futex','syscalls:sys_enter_read','syscalls:sys_enter_write'];assert all(k in counts for k in names)
  lines.append(f'| {w}/{n}/{d} | {v} | '+' | '.join(f'{counts[k]:,.0f}' for k in names)+' |')
fast=read('empty-fast.json');fbuild=read('empty-fast-build.json')
assert fast['build']==fbuild
assert fbuild['source']==build['source']
assert fbuild['base_patch_sha256']==sha(root/'candidate.patch')
assert fbuild['additional_patch_sha256']==sha(root/'empty-fast.patch')
assert fast['runner']['sha256']==sha(root/'scripts/run.py')
assert fast['helper']['sha256']==sha(root/'scripts/sample-runner.py')
assert fast['client']['sha256']==echo['client']['sha256']
expected={(v,b,r) for v,b,r in itertools.product(['before','local','empty-fast'],['iouring','iouring-poll','tokio'],range(1,4)) if not (v=='local' and b=='tokio')}
actual=[(x['variant'],x['backend'],x['repeat']) for x in fast['samples']]
assert len(actual)==len(set(actual)) and set(actual)==expected
assert all((x['workers'],x['connections'],x['bytes'])==(1,1,64) for x in fast['samples'])
for case in fast['cases']:
 expected_binary=fbuild['binary'] if case['label']=='empty-fast' else build['binaries'][case['label']]['core-scheduler-echo-benchmark']
 assert case['binary']==expected_binary
lines+=['','## Follow-up: bypass empty-queue flushing','','Separate randomized single-worker/single-connection screen. `empty-fast.patch` adds an early empty check to the archived candidate. This did not establish a repeatable improvement; these samples are not substituted into the primary timer, echo, or mixed results.','','| Backend | Version | Requests/s (range) | Change versus before |','| --- | --- | ---: | ---: |']
summary['empty_fast']=[]
for b in ['iouring','iouring-poll','tokio']:
 baseline=median(x['requests_per_second'] for x in fast['samples'] if (x['variant'],x['backend'])==('before',b))
 for v in ['before','local','empty-fast']:
  samples=[x['requests_per_second'] for x in fast['samples'] if (x['variant'],x['backend'])==(v,b)]
  if not samples:continue
  rate=median(samples);change=100*(rate/baseline-1)
  summary['empty_fast'].append({'backend':b,'variant':v,'requests_per_second':rate,'min':min(samples),'max':max(samples),'change_percent':change})
  lines.append(f'| {b} | {v} | {rate:,.0f} ({min(samples):,.0f}–{max(samples):,.0f}) | {change:+.2f}% |')
(root/'summary.json').write_text(json.dumps(summary,indent=2)+'\n');(root/'tables.md').write_text('\n'.join(lines)+'\n')
print('Validated',len(timers['samples']),'timer,',len(echo['samples']),'echo,',len(mixed['samples']),'mixed and',len(stat['samples']),'counter samples, plus',len(fast['samples']),'empty-path samples.')
