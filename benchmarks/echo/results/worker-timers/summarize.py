#!/usr/bin/env python3
"""Validate this diagnostic's complete sample matrices and regenerate its tables."""
import hashlib,itertools,json,statistics
from pathlib import Path
root=Path(__file__).resolve().parent
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
read=lambda p:json.loads((root/p).read_text())
build=read('build.json')
assert build['patch_sha256']==sha(root/'candidate.patch')
assert build['harness_sha256']==sha(root/'scripts/timers.rs')
assert build['source']=='130cd4a67e526e80ba9a5e7e7ebbe81494bd903b'
timers=read('timers.json');echo=read('echo.json');stat=read('stat/results.json');slack=read('slack.json')
assert slack['timer_slack_ns']==1
for data,name in [(timers,'run-timers.py'),(stat,'stat-timers.py'),(slack,'run-slack.py')]:
 assert data['build']==build
 assert data['runner_sha256']==sha(root/'scripts'/name)
assert echo['build']==build
assert echo['runner']['sha256']==sha(root/'scripts/run.py')
assert echo['helper']['sha256']==sha(root/'scripts/sample-runner.py')
assert echo['client']['sha256']=='db6c914ab75011477ec6232e681046b1e75532cbaa1c81663bac984591675cf3'
for case in echo['cases']:
 expected=build['binaries'][case['label']]['core-scheduler-echo-benchmark']
 assert case['binary']==expected
workloads=[(1,1,10),(1,1,1000),(1,32,1000),(1,1024,1000),(4,1,1000),(4,32,1000),(4,1024,1000)]
cases=[('before','iouring'),('integrated','iouring'),('before','native'),('before','tokio')]
expected={(v,b,w,n,d,r) for (v,b),(w,n,d),r in itertools.product(cases,workloads,range(1,4))}
actual=[(s['variant'],s['backend'],s['workers'],s['tasks'],s['delay_us'],s['repeat']) for s in timers['samples']]
assert len(actual)==len(set(actual)) and set(actual)==expected
workloads_echo=[(1,1,64),(1,32,64),(4,128,64)]
expected={(v,b,w,n,z,r) for v,b,(w,n,z),r in itertools.product(['before','integrated'],['iouring','iouring-poll','tokio'],workloads_echo,range(1,4))}
actual=[(s['variant'],s['backend'],s['workers'],s['connections'],s['bytes'],s['repeat']) for s in echo['samples']]
assert len(actual)==len(set(actual)) and set(actual)==expected
expected={(v,w,n,d,r) for v,(w,n,d),r in itertools.product(['before','integrated'],[(1,1,1000),(4,1,1000),(4,1024,1000)],range(1,3))}
actual=[(s['variant'],s['workers'],s['tasks'],s['delay_us'],s['repeat']) for s in stat['samples']]
assert len(actual)==len(set(actual)) and set(actual)==expected
expected={(v,'iouring',w,n,d,r) for v,(w,n,d),r in itertools.product(['before','integrated'],[(1,1,10),(1,1,1000),(1,32,1000),(4,1,1000),(4,1024,1000)],range(1,4))}
actual=[(s['variant'],s['backend'],s['workers'],s['tasks'],s['delay_us'],s['repeat']) for s in slack['samples']]
assert len(actual)==len(set(actual)) and set(actual)==expected
median=statistics.median
def aggregate(samples):
 return {k:median(s[k] for s in samples) for k in samples[0] if all(isinstance(s[k],(float,int)) for s in samples)}
def timer_group(variant,backend,w,n,d,data=timers):
 ss=[s for s in data['samples'] if (s['variant'],s['backend'],s['workers'],s['tasks'],s['delay_us'])==(variant,backend,w,n,d)]
 result=aggregate(ss);result['cpu_seconds']=median(s['user_seconds']+s['system_seconds'] for s in ss)
 result['rate_min']=min(s['expiries_per_second'] for s in ss);result['rate_max']=max(s['expiries_per_second'] for s in ss)
 return result
def echo_group(variant,backend,w,n,z):
 ss=[s for s in echo['samples'] if (s['variant'],s['backend'],s['workers'],s['connections'],s['bytes'])==(variant,backend,w,n,z)]
 rates=[s['requests_per_second'] for s in ss]
 return {'requests_per_second':median(rates),'min':min(rates),'max':max(rates)}
lines=['# Worker timer measurements','','Generated by `summarize.py`; uninstrumented rates are medians of three repetitions. Timer CPU is whole-process user + system time, including one second of warmup and three seconds of measurement. Lateness is measured at task resumption.','','## Timer integration','','| Workers / tasks / delay µs | Before expiries/s | Integrated expiries/s | Change | Before p50 / p99 µs | Integrated p50 / p99 µs | Before / integrated CPU seconds | Before / integrated threads |','| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
summary={'timers':[],'controls':[],'echo':[],'stat':[],'slack':[]}
for w,n,d in workloads:
 old=timer_group('before','iouring',w,n,d);new=timer_group('integrated','iouring',w,n,d);change=(new['expiries_per_second']/old['expiries_per_second']-1)*100
 summary['timers'].append({'workers':w,'tasks':n,'delay_us':d,'before':old,'integrated':new,'change_percent':change})
 lines.append(f"| {w}/{n}/{d} | {old['expiries_per_second']:,.0f} | {new['expiries_per_second']:,.0f} | {change:+.2f}% | {old['lateness_p50_us']:.2f} / {old['lateness_p99_us']:.2f} | {new['lateness_p50_us']:.2f} / {new['lateness_p99_us']:.2f} | {old['cpu_seconds']:.3f} / {new['cpu_seconds']:.3f} | {old['threads_at_250ms']:g} / {new['threads_at_250ms']:g} |")
lines+=['','## Matching timer slack at 1 ns','','Both processes inherit `PR_SET_TIMERSLACK = 1` before exec; newly created worker/timer threads inherit it. No machine-wide policy changes. This separates most of the default thread-wait coalescing from integration costs.','','| Workers / tasks / delay µs | Before expiries/s | Integrated expiries/s | Before p50 / p99 µs | Integrated p50 / p99 µs | Before / integrated CPU seconds |','| --- | ---: | ---: | ---: | ---: | ---: |']
for w,n,d in [(1,1,10),(1,1,1000),(1,32,1000),(4,1,1000),(4,1024,1000)]:
 old=timer_group('before','iouring',w,n,d,slack);new=timer_group('integrated','iouring',w,n,d,slack)
 summary['slack'].append({'workers':w,'tasks':n,'delay_us':d,'before':old,'integrated':new})
 lines.append(f"| {w}/{n}/{d} | {old['expiries_per_second']:,.0f} | {new['expiries_per_second']:,.0f} | {old['lateness_p50_us']:.2f} / {old['lateness_p99_us']:.2f} | {new['lateness_p50_us']:.2f} / {new['lateness_p99_us']:.2f} | {old['cpu_seconds']:.3f} / {new['cpu_seconds']:.3f} |")
lines+=['','## Timer controls','','Tokio uses a coarser timer policy. These controls are observations of the requested deadlines, not equal-precision capacity comparisons.','','| Backend | Workers / tasks / delay µs | Expiries/s | p50 / p99 lateness µs | CPU seconds | Threads |','| --- | --- | ---: | ---: | ---: | ---: |']
for backend in ['native','tokio']:
 for w,n,d in workloads:
  value=timer_group('before',backend,w,n,d);summary['controls'].append({'backend':backend,'workers':w,'tasks':n,'delay_us':d,**value})
  lines.append(f"| {backend} | {w}/{n}/{d} | {value['expiries_per_second']:,.0f} | {value['lateness_p50_us']:.2f} / {value['lateness_p99_us']:.2f} | {value['cpu_seconds']:.3f} | {value['threads_at_250ms']:g} |")
lines+=['','## Echo without application timers','','| Backend | Workers / connections / bytes | Before requests/s (range) | Integrated requests/s (range) | Change |','| --- | --- | ---: | ---: | ---: |']
for w,n,z in workloads_echo:
 for backend in ['iouring','iouring-poll','tokio']:
  old=echo_group('before',backend,w,n,z);new=echo_group('integrated',backend,w,n,z);change=(new['requests_per_second']/old['requests_per_second']-1)*100
  summary['echo'].append({'backend':backend,'workers':w,'connections':n,'bytes':z,'before':old,'integrated':new,'change_percent':change})
  lines.append(f"| {backend} | {w}/{n}/{z} | {old['requests_per_second']:,.0f} ({old['min']:,.0f}–{old['max']:,.0f}) | {new['requests_per_second']:,.0f} ({new['min']:,.0f}–{new['max']:,.0f}) | {change:+.2f}% |")
lines+=['','## Instrumented timer diagnostics','','These are separate whole-process `perf stat` medians of two runs. Counts include warmup, startup and shutdown; they are not divided by the measured-only timer count. Instrumented rates are excluded from capacity conclusions.','','| Workers / tasks / delay µs | Version | Instructions | Context switches | Ring enters | Futex calls | Reads | Writes |','| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
for w,n,d in [(1,1,1000),(4,1,1000),(4,1024,1000)]:
 for v in ['before','integrated']:
  counts={}
  for s in stat['samples']:
   if (s['variant'],s['workers'],s['tasks'],s['delay_us'])!=(v,w,n,d):continue
   for line in (root/'stat'/(s['identifier']+'.stat')).read_text().splitlines():
    parts=line.split(';')
    if len(parts)<3 or parts[0].startswith('#'):continue
    try: value=float(parts[0])
    except ValueError: continue
    counts.setdefault(parts[2].strip(),[]).append(value)
  counts={k:median(vs) for k,vs in counts.items()};summary['stat'].append({'variant':v,'workers':w,'tasks':n,'delay_us':d,'counts':counts})
  names=['instructions','context-switches','syscalls:sys_enter_io_uring_enter','syscalls:sys_enter_futex','syscalls:sys_enter_read','syscalls:sys_enter_write']
  assert all(k in counts for k in names),counts
  lines.append(f'| {w}/{n}/{d} | {v} | '+ ' | '.join(f'{counts[k]:,.0f}' for k in names)+' |')
(root/'summary.json').write_text(json.dumps(summary,indent=2)+'\n')
(root/'tables.md').write_text('\n'.join(lines)+'\n')
print(f'Validated {len(timers["samples"])} timer, {len(echo["samples"])} echo, {len(slack["samples"])} slack-control and {len(stat["samples"])} stat samples.')
